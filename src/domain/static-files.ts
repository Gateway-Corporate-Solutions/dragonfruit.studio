export const STATIC_LIMIT = 20_000_000;
export interface StaticFile {
  path: string;
  mime: string;
  base64: string;
  size: number;
}
const hasControls = (value: string) =>
  Array.from(value).some((char) =>
    char.charCodeAt(0) < 32 || char.charCodeAt(0) === 127
  );
const fail = (message: string): never => {
  throw new ValidationError([message]);
};
export function staticPath(value: string): string {
  if (typeof value === "string") {
    value = value.replace(/^(?:(?:static|public)\/)+/, "");
  }
  if (
    typeof value !== "string" || !value || value.length > 240 ||
    value !== value.normalize("NFC") || value.startsWith("/") ||
    /[\\%<>:"|?*]/.test(value) || hasControls(value) ||
    value.split("/").some((p) => !p || p === "." || p === "..")
  ) {
    return fail(
      "Use a relative static path without empty segments, traversal, or reserved filename characters",
    );
  }
  if (value === "runtime.js" || value === "index.html") {
    return fail(
      value +
        " is generated by the application. Choose another static filename",
    );
  }
  return value;
}
export function staticMime(path: string): string {
  const ext = path.split(".").at(-1)!.toLowerCase();
  const types: Record<string, string> = {
    png: "image/png",
    apng: "image/png",
    jpg: "image/jpeg",
    jpeg: "image/jpeg",
    gif: "image/gif",
    webp: "image/webp",
    avif: "image/avif",
    svg: "image/svg+xml",
    ico: "image/x-icon",
    json: "application/json",
    webmanifest: "application/manifest+json",
    css: "text/css",
    js: "text/javascript",
    mjs: "text/javascript",
    ts: "text/plain",
    tsx: "text/plain",
    jsx: "text/plain",
    html: "text/html",
    htm: "text/html",
    txt: "text/plain",
    md: "text/markdown",
    csv: "text/csv",
    xml: "application/xml",
    pdf: "application/pdf",
    woff2: "font/woff2",
    woff: "font/woff",
    ttf: "font/ttf",
    otf: "font/otf",
    mp4: "video/mp4",
    webm: "video/webm",
    mp3: "audio/mpeg",
    ogg: "audio/ogg",
    wav: "audio/wav",
    wasm: "application/wasm",
  };
  return Object.hasOwn(types, ext) ? types[ext] : "application/octet-stream";
}
export const base64Size = (value: string) =>
  Math.floor(value.length * 3 / 4) -
  (value.endsWith("==") ? 2 : value.endsWith("=") ? 1 : 0);
export function encodeBytes(bytes: Uint8Array): string {
  let text = "";
  for (let offset = 0; offset < bytes.length; offset += 32768) {
    text += String.fromCharCode(...bytes.subarray(offset, offset + 32768));
  }
  return btoa(text);
}
export const decodeFile = (file: StaticFile) =>
  Uint8Array.from(atob(file.base64), (c) => c.charCodeAt(0));
export function optimizeText(bytes: Uint8Array, path: string): Uint8Array {
  if (!/\.(json|webmanifest)$/i.test(path)) return bytes;
  try {
    const text = new TextDecoder("utf-8", { fatal: true }).decode(bytes)
      .replace(/^\uFEFF/, "");
    JSON.parse(text); // Validate syntax, but preserve numeric literals and string escapes exactly.
    let compactText = "", quoted = false, escaped = false;
    for (const char of text) {
      if (quoted) {
        compactText += char;
        if (escaped) escaped = false;
        else if (char === "\\") escaped = true;
        else if (char === '"') quoted = false;
      } else if (char === '"') {
        quoted = true;
        compactText += char;
      } else if (!/[ \t\r\n]/.test(char)) compactText += char;
    }
    const compact = new TextEncoder().encode(compactText);
    return compact.length < bytes.length ? compact : bytes;
  } catch {
    return bytes;
  }
}
export function parseStaticFiles(value: unknown): StaticFile[] {
  if (value === undefined) return [];
  if (!Array.isArray(value) || value.length > 500) {
    return fail("A static folder supports up to 500 files");
  }
  let total = 0;
  const paths = new Set<string>();
  return value.map((item) => {
    if (!item || typeof item !== "object") return fail("Invalid static file");
    const path = staticPath(item.path);
    if (paths.has(path)) {
      return fail("Static filenames must be unique: " + path);
    }
    paths.add(path);
    const data = item.base64;
    if (
      typeof data !== "string" || data.length > Math.ceil(64_000_000 / 3) * 4 ||
      data.length % 4 !== 0 || !/^[A-Za-z0-9+/]*={0,2}$/.test(data)
    ) return fail("Invalid or oversized static file data");
    // Compact JSON again on the server; browser-provided sizes and MIME types are not trusted.
    const file = {
      path,
      mime: staticMime(path),
      base64: data,
      size: base64Size(data),
    };
    if (/\.(json|webmanifest)$/i.test(path)) {
      const bytes = optimizeText(decodeFile(file), path);
      file.base64 = encodeBytes(bytes);
      file.size = bytes.length;
    }
    total += file.size;
    if (total > STATIC_LIMIT) {
      return fail("Static resources exceed 20 MB after optimization");
    }
    return file;
  });
}
export function parseStaticDirectories(
  value: unknown,
  files: StaticFile[],
): string[] {
  if (value === undefined) value = [];
  if (!Array.isArray(value) || value.length > 500) {
    return fail("Use up to 500 static directories");
  }
  const result = [...new Set((value as string[]).map(staticPath))];
  const all = new Set(files.map((f) => f.path));
  for (const path of [...result, ...files.map((f) => f.path)]) {
    for (let i = path.indexOf("/"); i >= 0; i = path.indexOf("/", i + 1)) {
      if (all.has(path.slice(0, i))) {
        return fail("A static filename cannot also be a directory");
      }
    }
  }
  for (const path of result) {
    if (all.has(path)) {
      return fail("A static filename cannot also be a directory");
    }
  }
  return result.sort();
}
/** Relative file references are rooted at static; explicit ./ and ../ follow page URL semantics. */
export function relativeAssetUrl(value: string): boolean {
  return value.length <= 2000 && !/^[a-z][a-z0-9+.-]*:|^\/\//i.test(value) &&
    !/[\s<>"'\\]/.test(value) && !hasControls(value) &&
    /^(?:\.\.?\/)*[^?#]+\.[a-z0-9]+(?:[?#].*)?$/i.test(value);
}
export function resourceUrl(value: string, pagePath = "/"): string {
  if (
    !value || value.startsWith("#") || /^[a-z][a-z0-9+.-]*:|^\/\//i.test(value)
  ) return value;
  if (/^\/?(?:\.\/)?(?:static|public)\//.test(value)) {
    return "/" +
      value.replace(/^(?:\/?(?:\.\/)?(?:static|public)\/)+/, "").replace(
        /^\/+/,
        "",
      );
  }
  if (value.startsWith("/")) return value;
  if (relativeAssetUrl(value)) {
    if (/^\.\.?\//.test(value)) {
      return new URL(value, "https://static.invalid" + pagePath).pathname +
        new URL(value, "https://static.invalid" + pagePath).search +
        new URL(value, "https://static.invalid" + pagePath).hash;
    }
    return "/" + value;
  }
  return value;
}
export function findStaticFile(
  value: string,
  files: StaticFile[],
  pagePath = "/",
): StaticFile | undefined {
  const url = resourceUrl(value, pagePath);
  if (!url.startsWith("/") || url.startsWith("//")) return;
  try {
    const path = decodeURIComponent(url.split(/[?#]/)[0].slice(1));
    return files.find((f) => f.path === path);
  } catch {
    return;
  }
}
export const staticDataUrl = (file: StaticFile) =>
  "data:" + file.mime + ";base64," + file.base64;
const socialSizes = new Map<string, number>();
export function staticUsage(website: WebsiteDocument) {
  const userBytes = (website.staticFiles ?? []).reduce(
    (sum, f) => sum + base64Size(f.base64),
    0,
  );
  const images = new Set<string>();
  const visit = (nodes: typeof website.pages[number]["nodes"]) =>
    nodes.forEach((n) => {
      if (n.layer?.src?.startsWith("data:image/")) images.add(n.layer.src);
      for (const item of n.layer?.items ?? []) {
        if (item.image.startsWith("data:image/")) images.add(item.image);
      }
      visit(n.children);
    });
  website.pages.forEach((p) => visit(p.nodes));
  for (const p of website.commerce?.products ?? []) {
    if (p.image.startsWith("data:image/")) images.add(p.image);
  }
  let generatedBytes =
    new TextEncoder().encode(RUNTIME_SOURCE + "\nmount(document);\n").length;
  for (const value of images) {
    generatedBytes += base64Size(value.slice(value.indexOf(",") + 1));
  }
  for (const font of fontsForNodes(website.pages.flatMap((p) => p.nodes))) {
    for (const file of FONT_DATA[font.id].files) {
      generatedBytes += base64Size(file.base64);
    }
  }
  for (const page of website.pages) {
    const key = JSON.stringify([page.title, website.title]);
    let size = socialSizes.get(key);
    if (size === undefined) {
      size = socialPng(page.title, website.title).byteLength;
      if (socialSizes.size > 128) {
        socialSizes.delete(socialSizes.keys().next().value!);
      }
      socialSizes.set(key, size);
    }
    generatedBytes += size;
  }
  return {
    bytes: userBytes + generatedBytes,
    userBytes,
    generatedBytes,
    limit: STATIC_LIMIT,
  };
}
export function assertStaticBudget(website: WebsiteDocument): void {
  const generated = new Set([
    "runtime.js",
    "index.html",
    ...website.pages.map((page) => socialPath(page.path).slice(1)),
  ]);
  for (
    const font of fontsForNodes(website.pages.flatMap((page) => page.nodes))
  ) {
    for (const file of FONT_DATA[font.id].files) {
      generated.add(
        "fonts/" + font.id + "/" + file.name,
      );
    }
  }
  const images = new Set<string>();
  const visit = (nodes: typeof website.pages[number]["nodes"]) =>
    nodes.forEach((n) => {
      if (n.layer?.src?.startsWith("data:image/")) images.add(n.layer.src);
      for (const i of n.layer?.items ?? []) {
        if (i.image.startsWith("data:image/")) images.add(i.image);
      }
      visit(n.children);
    });
  website.pages.forEach((p) => visit(p.nodes));
  for (const p of website.commerce?.products ?? []) {
    if (p.image.startsWith("data:image/")) images.add(p.image);
  }
  let index = 0;
  for (const value of images) {
    const ext = value.slice(11, value.indexOf(";"));
    generated.add(
      "media/image-" + (++index) + "." + (ext === "jpeg" ? "jpg" : ext),
    );
  }
  for (const file of website.staticFiles ?? []) {
    for (const path of generated) {
      if (
        file.path === path || file.path.startsWith(path + "/") ||
        path.startsWith(file.path + "/")
      ) fail("Static path conflicts with a generated asset: " + file.path);
    }
  }
  for (const dir of website.staticDirectories ?? []) {
    for (const path of generated) {
      if (dir === path || dir.startsWith(path + "/")) {
        fail("Static directory conflicts with a generated asset: " + dir);
      }
    }
  }

  if (staticUsage(website).bytes > STATIC_LIMIT) {
    fail(
      "Static resources exceed 20 MB after optimization, including generated images and fonts. Remove files or choose smaller images",
    );
  }
}
