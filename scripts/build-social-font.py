"""Build the deterministic embed font from bundled OFL Inter.

Requires Pillow, fonttools[woff], and brotli. No network or runtime fonts needed.
"""
import base64
from io import BytesIO
import json
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
sources = []
for path in sorted((ROOT / 'assets/fonts/inter').glob('*.woff2')):
    font = TTFont(path)
    cmap = font.getBestCmap()
    font = instantiateVariableFont(font, {'wght': 600})
    font.flavor = None
    stream = BytesIO()
    font.save(stream)
    sources.append((stream.getvalue(), cmap))

characters = list(range(32, 384)) + list(range(0x2010, 0x2028)) + [0x20ac]
atlas = {}
for size in [28, 52, 64]:
    fonts = [(ImageFont.truetype(BytesIO(data), size), cmap) for data, cmap in sources]
    glyphs = {}
    for code in characters:
        source = next((f for f, cmap in fonts if code in cmap), None)
        if source is None:
            continue
        char = chr(code)
        left, top, right, bottom = source.getbbox(char, anchor='ls')
        width, height = right - left, bottom - top
        image = Image.new('L', (max(1, width), max(1, height)))
        ImageDraw.Draw(image).text((-left, -top), char, font=source, fill=255, anchor='ls')
        # Seven-bit coverage indexes the shared antialiasing palette.
        values = [round(v / 255 * 127) for v in image.tobytes()]
        runs = bytearray()
        for value in values:
            if runs and runs[-1] == value and runs[-2] < 255:
                runs[-2] += 1
            else:
                runs.extend((1, value))
        glyphs[char] = [round(source.getlength(char), 2), left, top, width, height,
                        base64.b64encode(runs).decode()]
    atlas[size] = glyphs

target = ROOT / 'src/domain/social-font.ts'
target.write_text('// Generated by scripts/build-social-font.py from OFL Inter.\n'
                  '// License: assets/fonts/inter/OFL.txt\n'
                  'export type SocialGlyph = [number, number, number, number, number, string];\n'
                  'export const SOCIAL_FONT: Record<number, Record<string, SocialGlyph>> = ' +
                  json.dumps(atlas, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(f'Wrote {target.name}: {target.stat().st_size:,} bytes')
