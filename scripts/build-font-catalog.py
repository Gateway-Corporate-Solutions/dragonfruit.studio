"""Refresh the bundled OFL web-font catalog from Google Fonts' public distributions."""
import base64
import concurrent.futures
import json
from pathlib import Path
import re
import urllib.parse
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
FAMILIES = [
    ('inter', 'Inter', 'Sans serif', '100..900', 'Modern and neutral'),
    ('dmsans', 'DM Sans', 'Sans serif', '100..1000', 'Clean and geometric'),
    ('nunito', 'Nunito', 'Sans serif', '200..1000', 'Soft and rounded'),
    ('lora', 'Lora', 'Serif', '400..700', 'Warm and literary'),
    ('playfairdisplay', 'Playfair Display', 'Serif', '400..900', 'Elegant editorial contrast'),
    ('merriweather', 'Merriweather', 'Serif', '300..900', 'Sturdy and readable'),
    ('oswald', 'Oswald', 'Display', '200..700', 'Tall and condensed'),
    ('bebasneue', 'Bebas Neue', 'Display', '400', 'Bold all-capital headlines'),
    ('spacemono', 'Space Mono', 'Monospace', '400;700', 'Geometric typewriter'),
    ('firacode', 'Fira Code', 'Monospace', '300..700', 'Code with programming ligatures'),
    ('caveat', 'Caveat', 'Handwritten & script', '400..700', 'Casual handwritten notes'),
    ('dancingscript', 'Dancing Script', 'Handwritten & script', '400..700', 'Flowing cursive'),
]
UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128.0.0.0 Safari/537.36'
def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': UA}), timeout=30) as response:
        return response.read()

def family(row):
    slug, name, group, weights, description = row
    css_url = 'https://fonts.googleapis.com/css2?' + urllib.parse.urlencode({'family':name+':wght@'+weights,'display':'swap'})
    css = fetch(css_url).decode()
    license_url = 'https://raw.githubusercontent.com/google/fonts/main/ofl/'+slug+'/OFL.txt'
    license_text = fetch(license_url).decode()
    if 'SIL OPEN FONT LICENSE Version 1.1' not in license_text:
        raise ValueError('Missing verified OFL license for '+name)
    urls = list(dict.fromkeys(re.findall(r'url\((https://fonts\.gstatic\.com/[^)]+)\)',css)))
    if not urls or "format('woff2')" not in css:
        raise ValueError('Expected WOFF2 font faces for '+name)
    folder = ROOT/'assets/fonts'/slug
    folder.mkdir(parents=True,exist_ok=True)
    (folder/'OFL.txt').write_text(license_text)
    files = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
        binaries = list(pool.map(fetch,urls))
    for index,(url,data) in enumerate(zip(urls,binaries)):
        if data[:4] != b'wOF2':
            raise ValueError('Not a WOFF2 font: '+url)
        filename = f'{slug}-{index+1}.woff2'
        (folder/filename).write_bytes(data)
        files.append({'name':filename,'base64':base64.b64encode(data).decode(),'source':url})
        css = css.replace(url,'__FONT_BASE__/'+filename)
    generic = 'serif' if group=='Serif' else 'monospace' if group=='Monospace' else 'cursive' if group=='Handwritten & script' else 'sans-serif'
    metadata = {'id':slug,'name':name,'group':group,'description':description,'stack':'"'+name+'", '+generic,'licenseUrl':license_url,'cssSource':css_url}
    (folder/'sources.json').write_text(json.dumps({**metadata,'files':[{k:v for k,v in f.items() if k!='base64'} for f in files]},indent=2)+'\n')
    return metadata, {'license':license_text,'css':css,'files':[{k:v for k,v in f.items() if k!='source'} for f in files]}

if __name__ == '__main__':
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        results = list(pool.map(family,FAMILIES))
    (ROOT/'src/domain/font-catalog.ts').write_text('// Generated by scripts/build-font-catalog.py. OFL licenses accompany the assets.\nexport const WEB_FONTS = '+json.dumps([r[0] for r in results],indent=2)+' as const;\n')
    (ROOT/'src/domain/font-assets.ts').write_text('// Generated by scripts/build-font-catalog.py. Do not hand-edit binary data.\nexport const FONT_DATA: Record<string, { license: string; css: string; files: {name: string; base64: string}[] }> = '+json.dumps({m['id']:v for m,v in results},ensure_ascii=True,separators=(',',':'))+';\n')
    print('Bundled',len(results),'OFL families;',sum(len(v['files']) for _,v in results),'WOFF2 files')
